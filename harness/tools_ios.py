    # -- files ---------------------------------------------------------------------

    @registry.tool(
        "list_files",
        "List files in the workspace, newest first. Use this to see what previous runs left behind.",
        {
            "type": "object",
            "properties": {
                "pattern": {"type": "string", "description": "Glob for the file name, e.g. '*.py'."},
                "subdir": {"type": "string", "description": "Limit the listing to this subdirectory."},
                "limit": {"type": "integer", "minimum": 1, "maximum": 1000, "description": "Max entries."},
            },
            "additionalProperties": False,
        },
        timeout=30.0,
    )
    def list_files(pattern: str = "*", subdir: str = "", limit: int = 200) -> ToolResult:
        root = workspace.resolve(subdir) if subdir else os.path.realpath(workspace.root)
        if not os.path.isdir(root):
            raise ToolError("{} is not a directory in the workspace".format(subdir))
        found = _iter_workspace_files(root, pattern, limit=int(limit or 200))
        if not found:
            return ToolResult.ok("No files matching {!r} in {}.".format(pattern, workspace.relative(root) or "."))
        rows = []
        for path in sorted(found, key=lambda p: -os.path.getmtime(p))[: int(limit or 200)]:
            stat = os.stat(path)
            rows.append(
                "{:>9}  {:>16}  {}".format(
                    stat.st_size, time.strftime("%Y-%m-%d %H:%M", time.localtime(stat.st_mtime)), workspace.relative(path)
                )
            )
        return ToolResult.ok(
            "{} file(s) in {}:\n{}".format(len(rows), workspace.relative(root) or ".", "\n".join(rows)),
            count=len(rows),
        )

    @registry.tool(
        "read_file",
        "Read a text file from the workspace. Use this before editing so your replacement text matches exactly.",
        {
            "type": "object",
            "properties": {
                "path": {"type": "string", "description": "Workspace-relative path."},
                "max_chars": {"type": "integer", "minimum": 1, "maximum": MAX_READ_CHARS},
            },
            "required": ["path"],
            "additionalProperties": False,
        },
        timeout=30.0,
    )
    def read_file(path: str, max_chars: int = 20000) -> ToolResult:
        target = workspace.resolve(path, must_exist=True)
        if os.path.isdir(target):
            raise ToolError("{} is a directory; use list_files".format(path))
