def _execute(
    *,
    target: Optional[str],
    source: Optional[str],
    argv: Sequence[str],
    cwd: str,
    timeout: float,
    input_values: Optional[Mapping[str, Any]] = None,
) -> Dict[str, Any]:
    """Run a program, choosing the mechanism the platform can actually honour.

    On a desktop the subprocess path is used because it is genuinely killable: the child
    gets its own session and a timeout terminates the whole process group.

    **On Pyto it is not.** ``subprocess.Popen`` there is an in-process shim: ``kill()``
    and ``terminate()`` are no-ops and ``os.fork`` is a stub, so a "timeout kill" would
    silently never kill anything while telling the user it had.  On device the program
    therefore runs in-process via ``runpy`` with redirected stdio and a *cooperative*
    timeout that raises inside the running code.
    """
    started = time.monotonic()
    if ios.has_fake_subprocess():
        return _run_in_process(
            target=target,
            source=source,
            argv=argv,
            cwd=cwd,
            timeout=timeout,
            started=started,
            input_values=input_values,
        )
    executable = sys.executable
    if target is not None and executable and os.path.exists(executable):
        try:
            return _run_subprocess_file(executable, target, argv, cwd, timeout, started, input_values=input_values)
        except OSError:
            pass  # e.g. the app bundle refuses to spawn; fall back to runpy
    return _run_in_process(
        target=target,
        source=source,
        argv=argv,
        cwd=cwd,
        timeout=timeout,
        started=started,
        input_values=input_values,
    )


def _run_subprocess_file(
    executable: str,
    target: str,
    argv: Sequence[str],
    cwd: str,
    timeout: float,
    started: float,
    *,
    input_values: Optional[Mapping[str, Any]] = None,
) -> Dict[str, Any]:
    if input_values is None:
        command = [executable, target] + list(argv)
    else:
        # The fixed wrapper uses argv (never a shell string) to pass a JSON object into
        # the same ``main(inputs)`` contract used by the in-process Pyto runner.
        runner = (
            "import json, runpy, sys\n"
            "target = sys.argv[1]\n"
            "values = json.loads(sys.argv[2])\n"
            "sys.argv = [target]\n"
            "namespace = runpy.run_path(target, run_name='pyto_saved_program')\n"
            "main = namespace.get('main')\n"
            "if not callable(main): raise SystemExit('input-enabled program must define main(inputs)')\n"
            "main(values)\n"
        )
        command = [executable, "-c", runner, target, json.dumps(dict(input_values), ensure_ascii=False)]
    popen_kwargs: Dict[str, Any] = {
        "stdout": subprocess.PIPE,
        "stderr": subprocess.PIPE,
        "stdin": subprocess.DEVNULL,
        "cwd": cwd,
        # The child is a program the model wrote: it gets no API key and no
        # PYTO_HARNESS_* configuration.  A real process boundary is the only place the
        # harness can enforce that, which is exactly why it is enforced here.
        "env": scrubbed_environ(),
    }
    if hasattr(os, "setsid"):
        # Its own session/process group, so a timeout can kill the whole tree rather
        # than leaving an orphan holding the pipe open.
        popen_kwargs["start_new_session"] = True
    process = subprocess.Popen(command, **popen_kwargs)  # type: ignore[arg-type]
    streams: Dict[str, Dict[str, Any]] = {}
    readers = []
    for name, pipe in (("stdout", process.stdout), ("stderr", process.stderr)):
        store: Dict[str, Any] = {"data": bytearray()}
        streams[name] = store
        readers.append(
            threading.Thread(
                target=_drain, args=(pipe, store, RUN_CAPTURE_BYTES), name="pyto-{}".format(name), daemon=True
            )
        )
    for reader in readers:
        reader.start()

    timed_out = False
    try:
        returncode = process.wait(timeout=timeout)
    except subprocess.TimeoutExpired:
        timed_out = True
        returncode = _terminate_group(process)
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:  # pragma: no cover - SIGKILL should be enough
            process.kill()
    for reader in readers:
        reader.join(timeout=5)

    note = ""
    if timed_out:
        note = "The program was still running after {}s and was killed (process group terminated).".format(timeout)
    capture_path = None
    truncated = any(store.get("truncated") for store in streams.values())
    if sum(len(store["data"]) for store in streams.values()) > RUN_CAPTURE_CHARS or truncated:
        capture_path = _spill_capture(cwd, target, streams)
        note = (note + " " if note else "") + "Full output saved to {}".format(capture_path)
    return {
        "mode": "subprocess",
        "stdout": _decode(streams["stdout"]),
        "stderr": _decode(streams["stderr"]),
        "returncode": returncode,
        "timed_out": timed_out,
        "timeout_enforced": True,  # a real process group was killed at the deadline
        "duration_s": time.monotonic() - started,
        "note": note,
        "capture_path": capture_path,
    }


def _drain(pipe: Any, store: Dict[str, Any], limit: int) -> None:
    """Read a pipe to exhaustion, keeping at most ``limit`` bytes."""
    if pipe is None:  # pragma: no cover - PIPE always yields a file object
        return
    try:
        while True:
            chunk = pipe.read(65536)
            if not chunk:
                break
            if len(store["data"]) < limit:
                store["data"].extend(chunk[: limit - len(store["data"])])
            else:
                store["truncated"] = True
    except (OSError, ValueError):  # pragma: no cover - pipe closed under us
        pass
    finally:
        try:
            pipe.close()
        except Exception:  # noqa: BLE001
            pass


def _terminate_group(process: "subprocess.Popen[bytes]") -> int:
    """SIGTERM the process group, then SIGKILL it.  Returns the best-known exit code."""
    killed_group = False
    if hasattr(os, "killpg") and hasattr(os, "getpgid"):
        try:
            os.killpg(os.getpgid(process.pid), signal.SIGTERM)
            killed_group = True
        except (ProcessLookupError, PermissionError, OSError):
            killed_group = False
    if not killed_group:
        try:
            process.terminate()
        except OSError:  # pragma: no cover
            pass
    try:
        return process.wait(timeout=3)
    except subprocess.TimeoutExpired:
        pass
    if killed_group:
        try:
            os.killpg(os.getpgid(process.pid), signal.SIGKILL)
        except (ProcessLookupError, PermissionError, OSError):  # pragma: no cover
            pass
    try:
        process.kill()
    except OSError:  # pragma: no cover
        pass
    try:
        return process.wait(timeout=3)
    except subprocess.TimeoutExpired:  # pragma: no cover
        return -9


def _decode(store: Mapping[str, Any]) -> str:
    text = bytes(store["data"]).decode("utf-8", "replace")
    if store.get("truncated"):
        text += "\n... [output exceeded {} KiB and was cut off]".format(RUN_CAPTURE_BYTES // 1024)
    if len(text) > RUN_CAPTURE_CHARS:
        text = text[:RUN_CAPTURE_CHARS] + "\n... [{} more characters]".format(len(text) - RUN_CAPTURE_CHARS)
    return text


def _spill_capture(cwd: str, target: Optional[str], streams: Mapping[str, Mapping[str, Any]]) -> Optional[str]:
    name = os.path.basename(target) if target else "inline"
    directory = os.path.join(cwd, "tool-output")
    try:
        mkdir_private(directory)
        path = os.path.join(directory, "run-{}-{}.log".format(name.replace(".py", ""), int(time.time() * 1000)))
        body = "### stdout\n{}\n### stderr\n{}".format(
            _decode(streams["stdout"]), _decode(streams["stderr"])
        )
        write_private(path, scrub_secrets(body))
        return path
    except OSError:  # pragma: no cover - filesystem dependent
        return None


class _BoundedTextSink(io.TextIOBase):
    """A write-through stdout/stderr sink that keeps at most ``limit`` characters.

    The previous shape was an unbounded :class:`io.StringIO` truncated *after* the program
    finished, so a program printing 64 MiB grew the process by 64 MiB before the
    20 000-character cap applied — on a phone with a ~500 MB watchdog that is exactly the
    crash the cap is documented to prevent.  This sink counts what it drops instead of
    keeping it, so peak memory is O(cap) rather than O(output).
    """

    def __init__(self, limit: int) -> None:
        super().__init__()
        self._limit = max(0, int(limit))
        self._lock = threading.Lock()
        self._chunks: List[str] = []
        self._kept = 0
        self._dropped = 0

    # -- io.TextIOBase surface a program (or `print`) may touch ---------------------

    def writable(self) -> bool:
        return True

    def isatty(self) -> bool:
        return False

    def flush(self) -> None:  # nothing is buffered outside the process
        return None

    @property  # type: ignore[override]
    def encoding(self) -> str:
        return "utf-8"

    def write(self, text: Any) -> int:
        if not isinstance(text, str):
            text = str(text)
        with self._lock:
            room = self._limit - self._kept
            if room > 0:
                kept = text[:room]
                self._chunks.append(kept)
                self._kept += len(kept)
            if len(text) > room:
                self._dropped += len(text) - max(room, 0)
        return len(text)

    def value(self) -> str:
        """The kept prefix plus the same marker ``_cap`` used to append."""
        with self._lock:
            text = "".join(self._chunks)
            if self._dropped:
                text += "\n... [{} more characters]".format(self._dropped)
            return text

    @property
    def dropped_chars(self) -> int:
        with self._lock:
            return self._dropped


def _run_in_process(
    *,
    target: Optional[str],
    source: Optional[str],
    argv: Sequence[str],
    cwd: str,
    timeout: float,
    started: float,
    input_values: Optional[Mapping[str, Any]] = None,
) -> Dict[str, Any]:
    """Run under a process-wide lease with redirected stdio and a cooperative timeout.

    A trace can stop ordinary Python bytecode, but cannot interrupt a native call or a
    child thread. The lease therefore stays owned by the worker until it has restored all
    interpreter globals; while a worker survives the deadline, another conflicting run
    is refused. This is concurrency control, not a sandbox or a guarantee that threads can
    be stopped.

    The program does not see the harness's credentials: ``os.environ`` is scrubbed for the
    duration of the run and restored in the worker's cleanup path.
    """
    try:
        lease = unix_tools.IN_PROCESS_EXECUTION_LANE.acquire("Python program")
    except ToolError as exc:
        return {
            "mode": "runpy",
            "stdout": "",
            "stderr": "",
            "returncode": 75,
            "timed_out": False,
            "timeout_enforced": True,
            "duration_s": time.monotonic() - started,
            "note": "Program was not started. {}".format(exc.message),
            "capture_path": None,
            "execution_lane_busy": True,
        }

    stdout_sink = _BoundedTextSink(RUN_CAPTURE_CHARS)
    stderr_sink = _BoundedTextSink(RUN_CAPTURE_CHARS)
    outcome: Dict[str, Any] = {}
    deadline = time.monotonic() + timeout

    def timeout_tracer(frame: Any, event: str, arg: Any) -> Any:
        if time.monotonic() > deadline:
            raise _ProgramTimeout("timed out after {:.1f}s".format(timeout))
        return timeout_tracer

    def body() -> None:
        """Run the program; every failure mode becomes an ``outcome`` entry."""
        try:
            os.chdir(cwd)
        except OSError as exc:
            # A deleted or unreadable workspace used to escape as a FileNotFoundError
            # traceback from outside the try: it is a clean, actionable tool error now.
            outcome["returncode"] = 1
            outcome["error"] = "the workspace {} is not usable: {}: {}".format(cwd, type(exc).__name__, exc)
            outcome["workspace_error"] = True
            stderr_sink.write(
                "[pyto-harness] {}\nRe-create the workspace (run.py does it automatically) and try again.\n".format(
                    outcome["error"]
                )
            )
            return
        sys.settrace(timeout_tracer)
        try:
            if target is not None:
                if input_values is None:
                    runpy.run_path(target, run_name="__main__")
                else:
                    namespace = runpy.run_path(target, run_name="pyto_saved_program")
                    entry = namespace.get("main")
                    if not callable(entry):
                        raise TypeError("input-enabled program must define main(inputs)")
                    entry(dict(input_values))
            else:
                exec(
                    compile(source or "", "<inline>", "exec"),
                    {"__name__": "__main__", "__file__": "<inline>"},
                )
            outcome["returncode"] = 0
        except _ProgramTimeout as exc:
            outcome["returncode"] = 124
            outcome["timed_out"] = True
            outcome["error"] = str(exc)
            stdout_sink.write("\n[pyto-harness] program stopped: {}\n".format(exc))
        except SystemExit as exc:
            code = exc.code
            outcome["returncode"] = 0 if code is None else (code if isinstance(code, int) else 1)
        except BaseException as exc:  # noqa: BLE001 - report it the way a traceback would
            import traceback

            traceback.print_exc(file=stderr_sink)
            outcome["returncode"] = 1
            outcome["error"] = "{}: {}".format(type(exc).__name__, exc)
        finally:
            # If the program cleared or replaced the tracer, the deadline did not apply to
            # it and the result must not imply that it did.
            outcome["tracer_intact"] = sys.gettrace() is timeout_tracer

    def wait_for_program_threads(baseline: set) -> None:
        """Do not restore shared streams/cwd while program-created threads are alive."""
        observed: Dict[int, str] = {}
        current_id = threading.current_thread().ident
        while True:
            active = [
                thread
                for thread in threading.enumerate()
                if thread.ident is not None
                and thread.ident != current_id
                and thread.ident not in baseline
                and thread.is_alive()
            ]
            for thread in active:
                observed[thread.ident or id(thread)] = thread.name
            if observed:
                outcome["program_threads"] = sorted(set(observed.values()))
            if not active:
                return
            # Re-scan after each short join so a surviving thread's newly spawned child
            # is also observed before the process globals are restored.
            for thread in active:
                thread.join(timeout=0.05)

    def run() -> None:
        saved_stdout, saved_stderr, saved_argv = sys.stdout, sys.stderr, sys.argv
        saved_trace = sys.gettrace()
        saved_environ_object = os.environ
        saved_environ = dict(saved_environ_object)
        original_cwd: Optional[str] = None
        try:
            sys.stdout, sys.stderr = stdout_sink, stderr_sink
            sys.argv = ([] if target is None else [target]) + list(argv)
            original_cwd = os.getcwd()
            baseline = {thread.ident for thread in threading.enumerate() if thread.ident is not None}
            outcome["baseline_threads"] = baseline
            with temporary_environ_scrub():
                body()
                # A spawned thread may still use cwd, environment, argv or redirected
                # output. Stop tracing this runner and retain ownership until those
                # threads exit. Native-blocked children may remain indefinitely.
                sys.settrace(saved_trace)
                wait_for_program_threads(baseline)
        except BaseException as exc:  # cleanup and report even when setup itself fails
            if outcome.get("returncode") in (None, 0):
                outcome["returncode"] = 1
            outcome.setdefault("error", "{}: {}".format(type(exc).__name__, exc))
            outcome.setdefault("workspace_error", isinstance(exc, OSError))
            try:
                stderr_sink.write("[pyto-harness] {}\n".format(outcome["error"]))
            except Exception:  # noqa: BLE001 - output capture must not prevent cleanup
                pass
        finally:
            if original_cwd is not None:
                try:
                    os.chdir(original_cwd)
                except OSError as exc:  # the program may have removed its own cwd
                    outcome["cwd_restore_error"] = "{}: {}".format(type(exc).__name__, exc)
                    if outcome.get("returncode") in (None, 0):
                        outcome["returncode"] = 1
            try:
                # Programs can mutate or replace os.environ. Restore the full mapping,
                # including non-secret variables, after the scrub context restores its
                # credential-shaped entries.
                os.environ = saved_environ_object
                saved_environ_object.clear()
                saved_environ_object.update(saved_environ)
            except BaseException as exc:  # environment restoration is part of ownership
                outcome["environment_restore_error"] = "{}: {}".format(type(exc).__name__, exc)
                if outcome.get("returncode") in (None, 0):
                    outcome["returncode"] = 1
            try:
                sys.settrace(saved_trace)
            finally:
                try:
                    sys.stdout, sys.stderr, sys.argv = saved_stdout, saved_stderr, saved_argv
                finally:
                    lease.release()

    worker = threading.Thread(target=run, name="pyto-runpy", daemon=True)
    lease.bind_worker(worker)
    try:
        worker.start()
    except BaseException as exc:
        lease.release()
        return {
            "mode": "runpy",
            "stdout": "",
            "stderr": "",
            "returncode": 1,
            "timed_out": False,
            "timeout_enforced": True,
            "duration_s": time.monotonic() - started,
            "note": "Could not start the program worker: {}: {}".format(type(exc).__name__, exc),
            "capture_path": None,
            "execution_lane_busy": False,
        }
    worker.join(timeout=timeout + 2.0)
    worker_alive = worker.is_alive()
    notes: List[str] = []
    execution_lane_busy = False
    cooperative_timed_out = bool(outcome.get("timed_out"))
    if worker_alive:
        baseline = outcome.get("baseline_threads", set())
        survivors = [
            thread
            for thread in threading.enumerate()
            if thread.ident is not None
            and thread.ident != worker.ident
            and thread.ident not in baseline
            and thread.is_alive()
        ]
        if survivors:
            reason = "program-created background thread(s) are still active"
        else:
            reason = "the program is blocked in native code or removed its cooperative timeout"
        lease.mark_deadline_exceeded(reason)
        execution_lane_busy = True
        outcome["timed_out"] = True
        outcome["returncode"] = 124
        notes.append(
            "The program was still running after {:.0f}s and could not be interrupted: {}. It may "
            "still change workspace files or process state. Conflicting runs, native operations "
            "and workspace access are refused until it exits; restart Pyto if it does not finish."
            .format(timeout, reason)
        )

    timed_out = cooperative_timed_out or worker_alive
    timeout_enforced = bool(outcome.get("tracer_intact", False)) and not worker_alive
    if cooperative_timed_out and not worker_alive:
        timeout_enforced = True
        notes.append(
            "The program was stopped cooperatively after {:.0f}s. A trace cannot interrupt "
            "native calls or work running in child threads.".format(timeout)
        )
    elif not timeout_enforced and not cooperative_timed_out and not worker_alive:
        notes.append(
            "The program removed the cooperative timeout (sys.settrace(None)); the {:.0f}s "
            "limit did not bound its Python execution.".format(timeout)
        )
    if outcome.get("program_threads") and not worker_alive:
        notes.append(
            "The program created background thread(s); the runner waited for them to exit "
            "before restoring process state: {}.".format(", ".join(outcome["program_threads"]))
        )
    if outcome.get("cwd_restore_error"):
        notes.append("Could not restore the original working directory: {}".format(outcome["cwd_restore_error"]))
    if outcome.get("environment_restore_error"):
        notes.append("Could not restore the process environment: {}".format(outcome["environment_restore_error"]))
    return {
        "mode": "runpy",
        "stdout": stdout_sink.value(),
        "stderr": stderr_sink.value(),
        "returncode": outcome.get("returncode", 1),
        "timed_out": timed_out,
        "timeout_enforced": timeout_enforced,
        "duration_s": time.monotonic() - started,
        "note": " ".join(notes),
        "capture_path": None,
        "execution_lane_busy": execution_lane_busy,
    }


def _cap(text: str) -> str:
    if len(text) <= RUN_CAPTURE_CHARS:
        return text
    return text[:RUN_CAPTURE_CHARS] + "\n... [{} more characters]".format(len(text) - RUN_CAPTURE_CHARS)


class _ProgramTimeout(BaseException):
    """Raised by the cooperative timeout tracer.

    Derives from ``BaseException`` so that a program's own ``except Exception`` cannot
    swallow its timeout — the same reason ``KeyboardInterrupt`` is not an ``Exception``.
    """


