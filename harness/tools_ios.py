@dataclass
class ToolContext:
    """Everything the tools need that is not an argument from the model."""

    workspace: Workspace
    spill_dir: str
    #: Set by ``finish``.
    finished: bool = False
    finish_message: str = ""
    #: Persistent user facts, loaded from ``memory.json`` in the workspace.
    memory_path: str = ""
    #: Names of the tools that were called, in order (diagnostics for the UI).
    calls: List[str] = field(default_factory=list)
    #: Test seam: counts how many times ``run_program`` happened, for E2E assertions.
    runs: int = 0
    #: Resolved configuration, when the CLI has one (the self-repair tools need it).
    config: Any = None
    #: Absolute path of the config file the doctor should inspect.
    config_path: str = ""
    #: Where health.json, capabilities.json and backups live.
    state_dir: str = ""
    #: Directory containing run.py and harness/ (the self-repair path jail root).
    harness_root: str = ""
    #: Gate every self-edit on the whole test suite instead of the covering subset.
    full_gate: bool = False
    #: The live registry is used only for explicit custom-tool enable/create operations.
    registry: Optional[ToolRegistry] = None
    #: Lazy, per-process cache of this Pyto build's command inventory.
    unix_inventory: Optional[Dict[str, Any]] = None
    #: Invalid custom tool manifests are reported to the agent but never executed.
    custom_tool_errors: List[str] = field(default_factory=list)

    def note_call(self, name: str) -> None:
        self.calls.append(name)


