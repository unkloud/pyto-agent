def memory_file(context: ToolContext) -> str:
    return context.memory_path or os.path.join(context.workspace.root, "memory.json")


def _load_memory(context: ToolContext) -> Dict[str, Any]:
    path = memory_file(context)
    if not os.path.exists(path):
        return {}
    try:
        with open(path, "r", encoding="utf-8") as handle:
            payload = json.load(handle)
    except (OSError, ValueError):
        # A corrupt memory file must not break the turn; keep the bad copy for the user.
        try:
            with open(path, "rb") as handle:
                write_private(path + ".corrupt", handle.read())
        except OSError:  # pragma: no cover - filesystem dependent
            pass
        return {}
    if not isinstance(payload, dict):
        return {}
    facts = payload.get("facts")
    if isinstance(facts, dict):
        return {str(k): v for k, v in facts.items()}
    return {}


def _guard_write(content: str, field: str) -> None:
    """Refuse a single write big enough to threaten the process on a memory-tight device."""
    size = len(content.encode("utf-8"))
    reason = budget.check_write_size(size)
    if reason:
        raise ToolError(
            "{}: {}. Write it in pieces with edit_file, or keep the data in a program that "
            "reads it from somewhere else.".format(field, reason)
        )

def _save_memory(context: ToolContext, facts: Mapping[str, Any]) -> None:
    path = memory_file(context)
    payload = {
        "version": 1,
        "updated_at": int(time.time()),
        "facts": {str(k): v for k, v in facts.items()},
    }
    mkdir_private(os.path.dirname(path) or ".")
    temporary = path + ".tmp"
    with open_private(temporary, truncate=True) as handle:
        json.dump(payload, handle, indent=2, ensure_ascii=False, sort_keys=True)
        handle.write("\n")
    os.replace(temporary, path)  # atomic: an iOS kill cannot leave half a memory file
    if os.name == "posix":
        # os.replace keeps the mode of the temporary; make the final name owner-only too.
        security_chmod(path)


def _render_fact(value: Any) -> str:
    if isinstance(value, str):
        return value
    return json.dumps(value, ensure_ascii=False)


