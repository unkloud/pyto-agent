    @registry.tool(
        "search_files",
        "Search the workspace for a regex or plain string. Use this to find where something lives before reading whole files.",
        {
            "type": "object",
            "properties": {
                "query": {"type": "string", "description": "Text or regular expression to look for."},
                "pattern": {"type": "string", "description": "File-name glob, default '*'."},
                "regex": {"type": "boolean", "description": "Treat the query as a regex (default false)."},
                "ignore_case": {"type": "boolean", "description": "Case-insensitive search (default true)."},
                "limit": {
                    "type": "integer",
                    "minimum": 1,
                    "maximum": MAX_SEARCH_LIMIT,
                    "description": "Max matching lines to return.",
                },
            },
            "required": ["query"],
            "additionalProperties": False,
        },
        timeout=60.0,
        resource_reads=("workspace",),
    )
    def search_files(
        query: str,
        pattern: str = "*",
        regex: bool = False,
        ignore_case: bool = True,
        limit: int = DEFAULT_SEARCH_LIMIT,
    ) -> ToolResult:
        if not query:
            raise ToolError("a non-empty query is required")
        flags = re.IGNORECASE if ignore_case else 0
        try:
            matcher = re.compile(query if regex else re.escape(query), flags)
        except re.error as exc:
            raise ToolError("invalid regular expression {!r}: {}".format(query, exc)) from None
        cap = max(1, min(int(limit or DEFAULT_SEARCH_LIMIT), MAX_SEARCH_LIMIT))
        hits: List[str] = []
        files_scanned = 0
        truncated_by_cap = False
        for path in _iter_workspace_files(os.path.realpath(workspace.root), pattern, limit=2000):
            try:
                if os.path.getsize(path) > MAX_SEARCH_FILE_BYTES:
                    continue
            except OSError:
                continue
            files_scanned += 1
            try:
                with open(path, "r", encoding="utf-8", errors="replace") as handle:
                    for number, line in enumerate(handle, start=1):
                        if matcher.search(line):
                            hits.append(
                                "{}:{}: {}".format(workspace.relative(path), number, line.rstrip()[:300])
                            )
                            if len(hits) >= cap:
                                truncated_by_cap = True
                                break
            except OSError:
                continue
            if truncated_by_cap:
                break
        if not hits:
            return ToolResult.ok(
                "No match for {!r} in {} file(s) scanned.".format(query, files_scanned), matches=0
            )
        footer = "\n[stopped at the {} match cap; narrow the query or raise limit]" if truncated_by_cap else ""
        return ToolResult.ok(
            "{} match(es) across {} file(s) scanned:\n{}{}".format(len(hits), files_scanned, "\n".join(hits), footer),
            matches=len(hits),
        )

