# --------------------------------------------------------------------------------------
# Workspace path jail
# --------------------------------------------------------------------------------------


class Workspace:
    """A directory that all file tools are confined to.

    The jail is enforced on the *resolved* path (``realpath``), so ``link/../../x`` and
    a symlink pointing outside the workspace are both caught before any I/O happens.
    """

    def __init__(self, root: str) -> None:
        # The same rule as every user-supplied path: a ``~`` is expanded or refused, so a
        # device without a home directory never gets a workspace literally named ``~``.
        self.root = expand_user_path(root, what="workspace")
        # 0700: the workspace holds the user's programs, the memory store and every spill
        # file (the complete output the model was not shown).  Created private, not
        # chmod'ed later.
        mkdir_private(self.root)

    def resolve(self, relative: str, *, must_exist: bool = False) -> str:
        """Map a model-supplied path to an absolute path inside the workspace."""
        raw = (relative or "").strip()
        if not raw:
            raise ToolError("a path is required")
        if "\x00" in raw:
            raise ToolError("the path contains a NUL byte")
        candidate = raw if os.path.isabs(raw) else os.path.join(self.root, raw)
        resolved = os.path.realpath(candidate)
        root = os.path.realpath(self.root)
        if resolved != root and not resolved.startswith(root + os.sep):
            raise ToolError(
                "refusing to touch {!r}: it resolves to {}, outside the workspace {}".format(
                    raw, resolved, root
                )
            )
        if must_exist and not os.path.exists(resolved):
            raise ToolError("no such file inside the workspace: {}".format(raw))
        return resolved

    def relative(self, absolute: str) -> str:
        try:
            return os.path.relpath(absolute, os.path.realpath(self.root))
        except ValueError:  # pragma: no cover - different drive on Windows
            return absolute


