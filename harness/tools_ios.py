"""The model-facing tool set, written for an agent helping an iOS user.

House style for every description: **what it does, then when to use it.**  One or two
sentences, no restating the parameter schema (the model already has that) and no
marketing.  A description that says "use this when the user asks for X" is worth more
than one that says "this tool is a powerful utility for X".

The file tools share a :class:`Workspace` path jail, so ``../../etc/passwd`` is refused
before it reaches the filesystem.  Everything here is synchronous on purpose: the
registry runs sync handlers in a worker thread, which is what makes a batch of tool
calls overlap instead of queueing behind the slowest one.
"""

