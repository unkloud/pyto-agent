def _read_text(path: str) -> Tuple[str, bool]:
    """Read a text file, returning ``(text, was_truncated)``.  Binary noise is refused."""
    size = os.path.getsize(path)
    with open(path, "rb") as handle:
        raw = handle.read(MAX_READ_CHARS * 4)
    if b"\x00" in raw[:4096]:
        raise ToolError("{} looks like a binary file; read_file only handles text".format(os.path.basename(path)))
    text = raw.decode("utf-8", "replace")
    if len(text) > MAX_READ_CHARS:
        return text[:MAX_READ_CHARS], True
    if size > len(raw):
        return text, True
    return text, False


def _iter_workspace_files(root: str, pattern: str = "*", limit: int = 5000) -> List[str]:
    """Walk the workspace deterministically, skipping the usual noise directories."""
    matches: List[str] = []
    for current, dirs, files in os.walk(root):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and not d.startswith("."))
        for name in sorted(files):
            if pattern in ("*", "") or fnmatch.fnmatch(name, pattern):
                matches.append(os.path.join(current, name))
                if len(matches) >= limit:
                    return matches
    return matches


def build_registry(context: ToolContext) -> ToolRegistry:
    """Create the registry containing every model-facing tool."""
    registry = ToolRegistry()
    context.registry = registry
    workspace = context.workspace

    def protect_custom_tool_store(target: str) -> None:
        relative = workspace.relative(os.path.realpath(target))
        first = relative.split(os.sep, 1)[0]
        if first == custom_tools.STORE_DIR:
            raise ToolError("custom tool files are managed by custom_tool_create/enable/disable; review them with custom_tool_list and read_file")

    # -- programs ------------------------------------------------------------------

    @registry.tool(
        "write_program",
        "Write a Python program into the workspace so it can be re-run later. "
        "Use this whenever the automation is worth keeping, instead of pasting code into chat.",
        {
            "type": "object",
            "properties": {
                "path": {
                    "type": "string",
                    "description": "File name inside the workspace, e.g. 'rename_shots.py'.",
                },
                "source": {"type": "string", "description": "The complete Python source."},
                "purpose": {
                    "type": "string",
                    "description": "One line describing what it does; becomes the file's header comment.",
                },
            },
            "required": ["path", "source"],
            "additionalProperties": False,
        },
    )
    def write_program(path: str, source: str, purpose: str = "") -> ToolResult:
        _guard_write(source, "source")
        target = workspace.resolve(path)
        if not target.endswith(".py"):
            target += ".py"
        protect_custom_tool_store(target)
        if os.path.isdir(target):
            raise ToolError("{} is a directory".format(workspace.relative(target)))
        header = PROGRAM_HEADER.format(
            purpose=(purpose or "an iOS automation").strip().splitlines()[0][:160],
            version="{}.{}".format(sys.version_info[0], sys.version_info[1]),
        )
        body = source if source.endswith("\n") else source + "\n"
        os.makedirs(os.path.dirname(target) or workspace.root, exist_ok=True)
        existed = os.path.exists(target)
        with open(target, "w", encoding="utf-8") as handle:
            handle.write(header + body)
        relative = workspace.relative(target)
        return ToolResult.ok(
            "{} {} ({} lines). Run it with run_program(\"{}\").".format(
                "Rewrote" if existed else "Wrote",
                relative,
                body.count("\n"),
                relative,
            ),
            path=relative,
            bytes=len(header) + len(body),
            overwrote=existed,
        )

    @registry.tool(
        "run_program",
        "Run a Python program and return its stdout/stderr. Pass a workspace path, or raw source to "
        "try something once. Use this to test what you wrote before telling the user it works. "
        "Keep programs short and non-blocking: on iOS they run inside this app, and a program stuck "
        "in a network call cannot be interrupted.",
        {
            "type": "object",
            "properties": {
                "path_or_source": {
                    "type": "string",
                    "description": "A workspace-relative .py path, or inline Python source.",
                },
                "args": {
                    "type": "array",
                    "items": {"type": "string"},
                    "description": "Command-line arguments passed to the program.",
                },
                "timeout_s": {
                    "type": "number",
                    "description": "Kill the program after this many seconds (default 30, max 300).",
                    "minimum": 0.5,
                    "maximum": MAX_RUN_TIMEOUT,
                },
            },
            "required": ["path_or_source"],
            "additionalProperties": False,
        },
        timeout=None,  # the subprocess has its own timeout; do not double-bound it
    )
    def run_program(
        path_or_source: str, args: Optional[Sequence[str]] = None, timeout_s: float = DEFAULT_RUN_TIMEOUT
    ) -> ToolResult:
        context.runs += 1
        argv = [str(a) for a in (args or [])]
        timeout = max(0.5, min(float(timeout_s or DEFAULT_RUN_TIMEOUT), MAX_RUN_TIMEOUT))
        looks_like_path = "\n" not in path_or_source and path_or_source.strip().endswith(".py")
        if looks_like_path:
            target = workspace.resolve(path_or_source.strip(), must_exist=True)
            source = None
            label = workspace.relative(target)
        else:
            target = None
            source = path_or_source
            label = "<inline source>"
        if ios.is_pyto():
            # Pyto's subprocess replacement changes process-wide cwd, streams, argv and env.
            # Share one execution lane with its embedded Unix commands to avoid cross-talk.
            with unix_tools.IN_PROCESS_EXECUTION_LOCK:
                outcome = _execute(target=target, source=source, argv=argv, cwd=workspace.root, timeout=timeout)
        else:
            outcome = _execute(target=target, source=source, argv=argv, cwd=workspace.root, timeout=timeout)
        outcome["program"] = label
        header = "{} {} in {:.2f}s ({} mode)".format(
            "TIMED OUT" if outcome["timed_out"] else ("FAILED" if outcome["returncode"] else "OK"),
            label,
            outcome["duration_s"],
            outcome["mode"],
        )
        sections = [header]
        if outcome.get("note"):
            sections.append(outcome["note"])
        if not outcome.get("timeout_enforced", True):
            # Never claim a bound that did not hold.
            sections.append("timeout enforced: false (the program removed the cooperative timeout)")
        sections.append("--- stdout ---\n{}".format(outcome["stdout"].rstrip() or "<empty>"))
        if outcome["stderr"].strip():
            sections.append("--- stderr ---\n{}".format(outcome["stderr"].rstrip()))
        sections.append("--- exit code: {} ---".format(outcome["returncode"]))
        hint = pyto_api.hint_for_stderr(outcome["stderr"], state_dir=context.state_dir or None)
        if hint:
            sections.append(hint)
        return ToolResult(
            content="\n".join(sections),
            is_error=bool(outcome["returncode"]) or outcome["timed_out"],
            metadata={
                "returncode": outcome["returncode"],
                "timed_out": outcome["timed_out"],
                "timeout_enforced": bool(outcome.get("timeout_enforced", True)),
                "mode": outcome["mode"],
                "capture_path": outcome.get("capture_path"),
                "stdout_chars": len(outcome["stdout"]),
                "stderr_chars": len(outcome["stderr"]),
                "pyto_hint": bool(hint),
            },
        )

