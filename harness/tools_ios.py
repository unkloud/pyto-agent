def default_context(workspace_dir: str, spill_dir: str = "", *, config: Any = None) -> ToolContext:
    """Build the tool context.

    ``config`` is the resolved :class:`harness.config.Config` when the CLI has one; the
    self-repair tools need it (and its path) to run the doctor with the same settings the
    user is running with.  Without it they fall back to a default configuration, so the
    registry is still constructible in a unit test or a preview.
    """
    from . import config as config_module

    workspace = Workspace(workspace_dir)
    resolved_config_path = expand_user_path(config_module.default_config_path(), what="config file path")
    return ToolContext(
        workspace=workspace,
        spill_dir=spill_dir or os.path.join(workspace.root, "tool-output"),
        memory_path=os.path.join(workspace.root, "memory.json"),
        config=config,
        config_path=resolved_config_path,
        state_dir=expand_user_path(config_module.default_state_dir(), what="state directory"),
        harness_root=os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    )


